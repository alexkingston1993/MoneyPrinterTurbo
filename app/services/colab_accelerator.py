def is_available() -> bool:
    """Check if the `colab` CLI is installed and usable."""
    return shutil.which("colab") is not None


def _generate_runner_script(
    script_path: str,
    audio_path: str,
    avatar_image_path: str,
    video_path: str,
    output_path: str,
) -> str:
    """Generate the Python script that will run on Colab's GPU."""
    return textwrap.dedent(f'''\
    """
    GPU-accelerated pipeline: Coqui TTS + avatar compositing.
    Generated by ColabAccelerator — runs on Colab GPU.
    """
    import os, sys, subprocess, time

    # Install GPU-compatible deps
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "TTS", "moviepy", "numpy", "Pillow", "scipy", "soundfile"], check=True)

    os.environ["COQUI_TOS_AGREED"] = "1"

    # Step 1: Coqui TTS (GPU-accelerated)
    if os.path.exists("{script_path}"):
        script_text = open("{script_path}").read()
        print(f"Script: {{len(script_text.split())}} words")

        from TTS.api import TTS
        import torch

        print(f"GPU available: {{torch.cuda.is_available()}}")
        if torch.cuda.is_available():
            print(f"Device: {{torch.cuda.get_device_name(0)}}")
        else:
            print("WARNING: No GPU detected, falling back to CPU")

        model = TTS("tts_models/multilingual/multi-dataset/xtts_v2")
        model.to("cuda" if torch.cuda.is_available() else "cpu")

        t0 = time.time()
        model.tts_to_file(
            text=script_text,
            file_path="{audio_path}",
            speaker_wav="{avatar_image_path}",
            language="en",
            speed=1.0,
        )
        elapsed = time.time() - t0
        audio_duration = 0
        if os.path.exists("{audio_path}"):
            import soundfile as sf
            data, sr = sf.read("{audio_path}")
            audio_duration = len(data) / sr
        print(f"TTS done: {{elapsed:.1f}}s for {{audio_duration:.1f}}s audio")

    # Step 2: Avatar compositing (GPU via PyTorch ops if available, else CPU)
    if os.path.exists("{video_path}") and os.path.exists("{avatar_image_path}"):
        from moviepy import VideoFileClip, CompositeVideoClip, VideoClip
        from PIL import Image, ImageEnhance
        import numpy as np
        import math

        video = VideoFileClip("{video_path}")
        duration = video.duration
        fps = video.fps or 30
        print(f"Video: {{video.w}}x{{video.h}}, {{duration:.1f}}s")

        # Process avatar
        pil_img = Image.open("{avatar_image_path}").convert("RGB")
        overlay_w = int(video.w * 0.28)
        aspect = pil_img.height / pil_img.width
        overlay_h = int(overlay_w * aspect)
        max_h = int(video.h * 0.45)
        if overlay_h > max_h:
            overlay_h = max_h
            overlay_w = int(overlay_h / aspect)
        pil_img = pil_img.resize((overlay_w, overlay_h), Image.LANCZOS)

        enhancer = ImageEnhance.Contrast(pil_img)
        pil_img = enhancer.enhance(1.1)
        enhancer = ImageEnhance.Sharpness(pil_img)
        pil_img = enhancer.enhance(1.05)

        img_array = np.array(pil_img)
        margin_x = int(video.w * 0.03)
        margin_y = int(video.h * 0.02)
        pos_x = video.w - overlay_w - margin_x
        pos_y = video.h - overlay_h - margin_y

        def make_frame(t):
            breath = 1.0 + 0.003 * math.sin(2 * math.pi * t / 3.0)
            cw = max(1, int(overlay_w * breath))
            ch = max(1, int(overlay_h * breath))
            from PIL import Image as PILImage
            frame_pil = PILImage.fromarray(img_array).resize((cw, ch), PILImage.LANCZOS)
            return np.array(frame_pil)

        overlay = VideoClip(make_frame, duration=duration)
        bob_y = lambda t: 1.5 * math.sin(2 * math.pi * t / 2.5)
        overlay = overlay.with_position(lambda t: (pos_x, pos_y + bob_y(t)))
        overlay = overlay.with_duration(duration)

        final = CompositeVideoClip([video, overlay])
        final.write_videofile(
            "{output_path}",
            codec="libx264",
            audio_codec="aac",
            fps=fps,
            threads=2,
        )
        video.close()
        final.close()
        print(f"Avatar compositing done: {{os.path.getsize('{output_path}') / 1e6:.1f}}MB")
    else:
        print("Missing files, skipping avatar compositing")
        shutil.copy("{video_path}", "{output_path}")

    print("Colab pipeline complete")
    ''')


def run_tts_and_avatar(
    script_path: str,
    video_path: str,
    avatar_image_path: str,
    output_path: str,
    gpu_type: str = "T4",
    timeout: int = 600,
) -> bool:
    """
    Run Coqui TTS + avatar compositing on a Colab GPU.

    Args:
        script_path: Path to the script text file
        video_path: Path to the combined video (without audio)
        avatar_image_path: Path to avatar image
        output_path: Where to save the final video
        gpu_type: GPU type (T4, L4, A100, etc.)
        timeout: Max execution time in seconds

    Returns:
        True if successful
    """
    if not is_available():
        logger.warning("Colab CLI not available — install with: uv tool install google-colab-cli")
        return False

    workdir = tempfile.mkdtemp(prefix="colab_work_")
    try:
        # Prepare files in workdir
        local_script = os.path.join(workdir, "script.txt")
        local_video = os.path.join(workdir, "input_video.mp4")
        local_avatar = os.path.join(workdir, "avatar.jpg")
        local_audio = os.path.join(workdir, "audio.mp3")
        local_output = os.path.join(workdir, "output_final.mp4")

        shutil.copy2(script_path, local_script)
        shutil.copy2(video_path, local_video)
        shutil.copy2(avatar_image_path, local_avatar)

        # Generate runner
        runner_path = os.path.join(workdir, "run_colab.py")
        runner_code = _generate_runner_script(
            script_path="/content/script.txt",
            audio_path="/content/audio.mp3",
            avatar_image_path="/content/avatar.jpg",
            video_path="/content/input_video.mp4",
            output_path="/content/output_final.mp4",
        )
        with open(runner_path, "w") as f:
            f.write(runner_code)

        logger.info(f"Colab accelerator: provisioning {gpu_type} GPU...")
        logger.info(f"  workdir: {workdir}")

        cmd = [
            "colab", "run",
            "--gpu", gpu_type,
            "--timeout", str(timeout),
            runner_path,
        ]

        t0 = time.time()
        result = subprocess.run(
            cmd,
            cwd=workdir,
            capture_output=True,
            text=True,
            timeout=timeout + 60,
        )
        elapsed = time.time() - t0

        if result.returncode != 0:
            logger.error(f"Colab pipeline failed (rc={result.returncode}):")
            logger.error(result.stderr[:2000])
            return False

        logger.success(f"Colab pipeline completed in {elapsed:.0f}s")

        # The script runs on Colab — we need to download the output.
        # Since `colab run` auto-teardowns, we handle download in the script
        # via Drive mount. For simplicity, let's use a different approach:
        # run `colab new` + `colab exec` + `colab download` manually.

        # Actually, `colab run` doesn't automatically download files.
        # We need to use `colab upload` before and `colab download` after.
        # Let's use a session-based approach instead.

        logger.warning("colab run doesn't auto-download files. Switching to session-based approach.")
        return _run_with_session(
            runner_path, workdir, local_output, output_path, gpu_type, timeout
        )

    except subprocess.TimeoutExpired:
        logger.error(f"Colab pipeline timed out after {timeout}s")
        return False
    except Exception as e:
        logger.error(f"Colab pipeline error: {e}")
        return False
    finally:
        if os.path.exists(workdir):
            shutil.rmtree(workdir, ignore_errors=True)


def _run_with_session(
    runner_path: str,
    workdir: str,
    local_output: str,
    final_output: str,
    gpu_type: str = "T4",
    timeout: int = 600,
) -> bool:
    """
    Session-based approach:
    1. colab new --gpu T4 -s myjob
    2. colab upload runner + inputs
    3. colab exec -f run.py
    4. colab download output
    5. colab stop
    """
    session_name = f"compounder_{int(time.time())}"
    try:
        # 1. Provision GPU
        logger.info(f"Creating session '{session_name}' with {gpu_type} GPU...")
        subprocess.run(
            ["colab", "new", "-s", session_name, "--gpu", gpu_type],
            capture_output=True, text=True, timeout=120,
            check=True,
        )
        logger.info("Session created")

        # 2. Upload files
        uploads = [
            (runner_path, "run_colab.py"),
        ]
        for local, remote in uploads:
            subprocess.run(
                ["colab", "upload", "-s", session_name, local, remote],
                capture_output=True, text=True, timeout=60,
                check=True,
            )
        logger.info("Files uploaded")

        # 3. Run the script
        logger.info(f"Executing on Colab (timeout={timeout}s)...")
        t0 = time.time()
        result = subprocess.run(
            ["colab", "exec", "-s", session_name, "-f", "run_colab.py"],
            capture_output=True, text=True, timeout=timeout + 120,
        )
        elapsed = time.time() - t0
        logger.info(f"Execution log:\n{result.stdout[:3000]}")
        if result.stderr:
            logger.warning(f"Execution stderr:\n{result.stderr[:2000]}")
        logger.info(f"Execution completed in {elapsed:.0f}s")

        # 4. Download output
        subprocess.run(
            ["colab", "download", "-s", session_name, "/content/output_final.mp4", local_output],
            capture_output=True, text=True, timeout=120,
        )

        if os.path.exists(local_output) and os.path.getsize(local_output) > 1000:
            shutil.move(local_output, final_output)
            logger.success(f"Output saved: {final_output} ({os.path.getsize(final_output)/1e6:.1f}MB)")
            return True
        else:
            logger.error("Output file not found on Colab or is empty")
            return False

    except subprocess.TimeoutExpired:
        logger.error(f"Session timed out after {timeout}s")
        return False
    except subprocess.CalledProcessError as e:
        logger.error(f"Session command failed: {e}")
        logger.error(f"stdout: {e.stdout[:1000] if e.stdout else ''}")
        logger.error(f"stderr: {e.stderr[:1000] if e.stderr else ''}")
        return False
    except Exception as e:
        logger.error(f"Session error: {e}")
        return False
    finally:
        try:
            subprocess.run(
                ["colab", "stop", "-s", session_name],
                capture_output=True, text=True, timeout=30,
            )
        except Exception:
            pass


def tts_on_colab(script_path: str, output_audio_path: str, voice_ref_path: str) -> bool:
    """Run Coqui TTS on Colab GPU and download the result."""
    # Build a minimal TTS-only script
    runner = textwrap.dedent(f'''\
    import os, subprocess, sys
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "TTS", "soundfile"], check=True)
    os.environ["COQUI_TOS_AGREED"] = "1"
    from TTS.api import TTS
    import torch
    print(f"GPU: {{torch.cuda.is_available()}}")
    text = open("/content/script.txt").read()
    model = TTS("tts_models/multilingual/multi-dataset/xtts_v2")
    model.to("cuda" if torch.cuda.is_available() else "cpu")
    model.tts_to_file(text=text, file_path="/content/audio.mp3", speaker_wav="/content/voice_ref.wav", language="en")
    print(f"Done: {{os.path.getsize('/content/audio.mp3')}} bytes")
    ''')

    tmpdir = tempfile.mkdtemp(prefix="colab_tts_")
    try:
        runner_path = os.path.join(tmpdir, "run_tts.py")
        with open(runner_path, "w") as f:
            f.write(runner)

        session_name = f"tts_{int(time.time())}"
        subprocess.run(["colab", "new", "-s", session_name, "--gpu", "T4"],
                       capture_output=True, text=True, timeout=120, check=True)
        subprocess.run(["colab", "upload", "-s", session_name, script_path, "script.txt"],
                       capture_output=True, text=True, timeout=60, check=True)
        subprocess.run(["colab", "upload", "-s", session_name, voice_ref_path, "voice_ref.wav"],
                       capture_output=True, text=True, timeout=60, check=True)
        subprocess.run(["colab", "upload", "-s", session_name, runner_path, "run_tts.py"],
                       capture_output=True, text=True, timeout=60, check=True)

        t0 = time.time()
        result = subprocess.run(["colab", "exec", "-s", session_name, "-f", "run_tts.py"],
                                capture_output=True, text=True, timeout=600)
        elapsed = time.time() - t0
        logger.info(f"Colab TTS: {elapsed:.0f}s\n{result.stdout[:1000]}")

        local_audio = os.path.join(tmpdir, "audio.mp3")
        subprocess.run(["colab", "download", "-s", session_name, "/content/audio.mp3", local_audio],
                       capture_output=True, text=True, timeout=120)
        if os.path.exists(local_audio) and os.path.getsize(local_audio) > 1000:
            shutil.move(local_audio, output_audio_path)
            logger.success(f"TTS audio saved: {output_audio_path}")
            return True
        return False
    finally:
        try:
            subprocess.run(["colab", "stop", "-s", session_name], capture_output=True, timeout=30)
        except Exception:
            pass
        shutil.rmtree(tmpdir, ignore_errors=True)
